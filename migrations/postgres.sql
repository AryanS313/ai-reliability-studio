CREATE TABLE IF NOT EXISTS prompt_versions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id BIGINT NOT NULL REFERENCES workspaces(id),
    prompt_id BIGINT NOT NULL REFERENCES prompts(id),
