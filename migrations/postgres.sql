-- Application connections set `ars.user_id` and `ars.workspace_id` after auth.
-- RLS is defense in depth; repository queries remain explicitly workspace-scoped.
DO $$
DECLARE table_name TEXT;
BEGIN
    FOREACH table_name IN ARRAY ARRAY[
        'projects','documents','document_versions','chunks','prompts','prompt_versions',
        'datasets','dataset_versions','targets','target_versions','eval_runs','executions',
        'scores','eval_results','judgments','comments','review_assignments','calibration_runs',
        'calibration_reviews','exports','audit_logs',
        'execution_cache','scheduled_evaluations'
    ] LOOP
        EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', table_name);
        IF NOT EXISTS (
            SELECT 1 FROM pg_policies WHERE schemaname = current_schema()
              AND tablename = table_name AND policyname = 'workspace_isolation'
        ) THEN
            EXECUTE format(
                'CREATE POLICY workspace_isolation ON %I USING (workspace_id = current_setting(''ars.workspace_id'', true)::bigint) WITH CHECK (workspace_id = current_setting(''ars.workspace_id'', true)::bigint)',
                table_name
            );
        END IF;
    END LOOP;
    ALTER TABLE memberships ENABLE ROW LEVEL SECURITY;
    IF NOT EXISTS (
        SELECT 1 FROM pg_policies WHERE schemaname = current_schema()
          AND tablename = 'memberships' AND policyname = 'membership_isolation'
    ) THEN
        CREATE POLICY membership_isolation ON memberships
          USING (
            user_id = NULLIF(current_setting('ars.user_id', true), '')::bigint
            OR workspace_id = NULLIF(current_setting('ars.workspace_id', true), '')::bigint
          )
          WITH CHECK (workspace_id = NULLIF(current_setting('ars.workspace_id', true), '')::bigint);
    END IF;
END $$;

